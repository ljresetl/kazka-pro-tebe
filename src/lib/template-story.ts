/** Скільки сюжетів є для кожної пригоди. */
export function plotCount(theme: ThemeId): number {
  return PLOTS[theme].length;
}

export function templateStory(
  req: StoryRequest,
  variant = 0,
): { title: string; dedication: string; pages: StoryPage[]; plotId: string } {
  const g = (m: string, f: string) => (req.gender === "boy" ? m : f);
  const trait = TRAIT_WORDS[req.trait] ?? TRAIT_WORDS["сміливість"];
  const friend = req.friend?.trim();
  const adj = g(trait.m, trait.f);

  const ctx: Ctx = {
    n: req.childName,
    g,
    years: yearsWord(req.age),
    adj,
    Adj: adj.replace(/^./, (ch) => ch.toUpperCase()),
    moral: trait.moral,
    friendLine: friend ? ` А поруч завжди був найкращий друг — ${friend}.` : "",
  };

  const plots = PLOTS[req.theme];
  const plot = plots[Math.abs(variant) % plots.length];
  const message = req.message?.trim();

  return {
    title: plot.title(ctx),
    dedication:
      message || `Цю казку створено для тебе, ${req.childName}. Нехай у твоєму житті буде багато добрих пригод.`,
    pages: plot.pages(ctx),
    plotId: plot.id,
  };
}
