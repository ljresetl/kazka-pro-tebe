// Шаблонні казки — працюють без ключа ШІ. Десять окремих сюжетів
// (по один-два на кожну пригоду); у текст підставляються ім'я, стать,
// вік, риса характеру й друг дитини. На кожній сторінці 3–5 речень.

export function yearsWord(age: number): string {
  const n = age % 100;
  const last = n % 10;
  if (n >= 11 && n <= 14) return `${age} років`;
  if (last === 1) return `${age} рік`;
  if (last >= 2 && last <= 4) return `${age} роки`;
  return `${age} років`;
}

