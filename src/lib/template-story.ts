// Шаблонні казки — працюють без ключа ШІ, прямо в браузері.
//
// 12 сюжетів (по два на кожну пригоду). Щоб казки не повторювалися,
// у текстах є розмітка:
//   {{варіант А|варіант Б|варіант В}} — обирається випадково;
//   [[додаткове речення]]           — лише для дітей від 4 років
//                                      (для 2–3 років казка коротша);
//   ${v.helper} тощо                 — імена й деталі, однакові в межах казки.
// Друг або улюбленець з'являється на початку, посеред пригоди й у фіналі.

export function yearsWord(age: number): string {
  const n = age % 100;
  const last = n % 10;
  if (n >= 11 && n <= 14) return `${age} років`;
  if (last === 1) return `${age} рік`;
  if (last >= 2 && last <= 4) return `${age} роки`;
  return `${age} років`;
}

type Ctx = {
  /** Ім'я дитини */
  n: string;
  /** Вибір слова за статтю: g("пішов", "пішла") */
  g: (m: string, f: string) => string;
  /** Вік словами: «5 років» */
  years: string;
  /** Прикметник-риса з великої літери: «Смілива», «Добрий»… */
  Adj: string;
  /** Той самий прикметник з малої літери */
  adj: string;
  /** Фінальне речення: друг (якщо є) + думка про рису характеру */
  ending: string;
  /** Речення про друга на першій сторінці або порожній рядок */
  friendLine: string;
  /** Деталі сюжету, обрані один раз на всю казку */
  v: Record<string, string>;
};

type Plot = {
  id: string;
  /** Варіанти імен і деталей: обирається один на всю казку. */
  vars?: Record<string, string[]>;
  title: (c: Ctx) => string;
  pages: (c: Ctx) => StoryPage[];
};

