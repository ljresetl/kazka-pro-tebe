export type NameEntry = { name: string; g: Gender; slug: string; gen: string; emoji: string; topic: string; letter: string };

const EMOJI: Record<Gender, string[]> = { m: ["👦", "🧒", "🌟", "🦁"], f: ["👧", "🌸", "🧚‍♀️", "🌟"] };

export const NAMES: NameEntry[] = ROWS.map(([name, gen, slug, g]) => ({
  name,
  g,
  slug,
  gen,
  emoji: pick(slug + "e", EMOJI[g]),
  topic: pick(slug, THEME_IDS),
  letter: name[0],
})).sort((a, b) => a.name.localeCompare(b.name, "uk"));

const BY_SLUG = new Map(NAMES.map((n) => [n.slug, n]));

export function getName(slug: string) {
  return BY_SLUG.get(slug);
}

/** Літери, на які є імена, в порядку абетки. */
export const NAME_LETTERS = [...new Set(NAMES.map((n) => n.letter))];

const LETTER_SLUG: Record<string, string> = Object.fromEntries(NAME_LETTERS.map((l) => [l, slugLetter(l)]));

function slugLetter(l: string) {
  const map: Record<string, string> = { А: "a", Б: "b", В: "v", Г: "h", Ґ: "g", Д: "d", Е: "e", Є: "ye", Ж: "zh", З: "z", И: "y", І: "i", Ї: "yi", Й: "y", К: "k", Л: "l", М: "m", Н: "n", О: "o", П: "p", Р: "r", С: "s", Т: "t", У: "u", Ф: "f", Х: "kh", Ц: "ts", Ч: "ch", Ш: "sh", Щ: "shch", Ю: "yu", Я: "ya" };
  return map[l] ?? l.toLowerCase();
}

export function letterSlug(l: string) {
  return LETTER_SLUG[l];
}

export function letterFromSlug(slug: string) {
  return NAME_LETTERS.find((l) => LETTER_SLUG[l] === slug);
}

export function namesByLetter(l: string) {
  return NAMES.filter((n) => n.letter === l);
}

export function namesForTopic(topic: string, limit: number) {
  const own = NAMES.filter((n) => n.topic === topic);
  const rest = NAMES.filter((n) => n.topic !== topic && pick(n.slug + topic, [0, 1, 2, 3, 4, 5, 6]) === 0);
  return [...own, ...rest].slice(0, limit);
}

/** Приклад героя для уривка на сторінці теми. */
export function exampleHero(topic: string) {
  const own = NAMES.filter((n) => n.topic === topic);
  return own[0] ?? pick(topic, NAMES);
}

/** Популярні імена для блоків «Улюблені імена». */
export function popularNames(seed: string, limit = 14) {
  const out: NameEntry[] = [];
  let i = 0;
  while (out.length < limit && i < 400) {
    const n = pick(`${seed}-${i++}`, NAMES);
    if (!out.includes(n)) out.push(n);
  }
  return out;
}

