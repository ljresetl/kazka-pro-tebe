export function nameTexts(n: NameEntry) {
  const topicLabel = findTopic(n.topic)?.topic.label.toLowerCase() ?? "";
  const f = (list: string[], k: string) => inflect(pick(n.slug + k, list).replace(/\{T\}/g, topicLabel), n.name, n.g, n.gen);
  const t = getThemeText(n.topic)!;
  return {
    lead: f(LEAD, "l"),
    paragraphs: [f(P1, "1"), f(P2, "2"), f(P3, "3"), f(P4, "4")],
    sample: inflect(t.sample, n.name, n.g, n.gen),
    titles: t.titles.map((x) => inflect(x, n.name, n.g, n.gen)),
    topicLabel: findTopic(n.topic)?.topic.label ?? "",
  };
}
